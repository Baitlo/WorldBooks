(function adaptXiyouForStudio() {
  const data = window.XIYOU_WORLDBOOK;
  const studio = window.XIYOU_STUDIO;
  if (!data || !studio) return;

  data.metadata = { ...data.metadata, ...studio.metadata };
  data.system_prompt = studio.systemPrompt;
  data.styles = studio.styles;

  Object.entries(studio.ruleOverrides).forEach(([id, content]) => {
    const rule = (data.rules || []).find(item => item.id === id);
    if (!rule) return;
    rule.content = content;
    if (id === "R07") rule.title = "文学语言与章回节奏";
    if (id === "R11") {
      rule.title = "三方向创作循环";
      rule.keywords = ["续写", "三方向", "自由输入"];
    }
    if (id === "R12") {
      rule.title = "分支独立与状态继承";
      rule.keywords = ["分支", "续写", "父节点", "时间线"];
    }
  });

  const replacePlayerLanguage = value => {
    if (typeof value === "string") {
      return value
        .replaceAll("玩家", "作者")
        .replaceAll("用户", "作者")
        .replaceAll("游戏", "故事");
    }
    if (Array.isArray(value)) return value.map(replacePlayerLanguage);
    if (value && typeof value === "object") {
      Object.keys(value).forEach(key => { value[key] = replacePlayerLanguage(value[key]); });
    }
    return value;
  };

  ["rules", "worldbuilding", "characters", "relationship_edges", "canon_timeline", "quests", "locations"]
    .forEach(key => { if (data[key]) data[key] = replacePlayerLanguage(data[key]); });
})();
