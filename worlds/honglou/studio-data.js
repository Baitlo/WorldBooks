(function adaptWorldbookForStudio() {
  const data = window.WORLDBOOK_DATA;
  if (!data) return;

  data.metadata = { ...data.metadata, ...STUDIO_DATA.metadata };
  data.system_prompt = STUDIO_DATA.systemPrompt;
  data.styles = STUDIO_DATA.styles;

  Object.entries(STUDIO_DATA.ruleOverrides).forEach(([id, content]) => {
    const rule = data.rules.find(item => item.id === id);
    if (rule) rule.content = content;
    if (rule && id === "R04") rule.title = "人物人格一致性";
    if (rule && id === "R07") rule.title = "文学语言与叙事节奏";
    if (rule && id === "R08") rule.title = "情节的因果与代价";
    if (rule && id === "R10") rule.title = "创作安全和人物主体性";
    if (rule && id === "R11") {
      rule.title = "三方向创作循环";
      rule.keywords = ["续写", "三方向", "自由输入"];
    }
    if (rule && id === "R12") {
      rule.title = "分支独立与状态继承";
      rule.keywords = ["分支", "续写", "父节点", "时间线"];
    }
  });

  const replacePlayerLanguage = value => {
    if (typeof value === "string") return value.replaceAll("玩家", "原创人物").replaceAll("游戏", "故事");
    if (Array.isArray(value)) return value.map(replacePlayerLanguage);
    if (value && typeof value === "object") {
      Object.keys(value).forEach(key => { value[key] = replacePlayerLanguage(value[key]); });
    }
    return value;
  };
  replacePlayerLanguage(data.rules);
  replacePlayerLanguage(data.characters);
  replacePlayerLanguage(data.quests);
  replacePlayerLanguage(data.canon_timeline);
  replacePlayerLanguage(data.relationship_edges);
})();
